# Which axes a person may narrow on, in the order a page should show them.
# `license_class` leads because it is the one that eliminates most sharply and
# the one a reader most often has a fixed answer to.
FACET_FIELDS = ("license_class", "domain_primary", "ecosystem", "maturity_stage",
                "deployment_target", "interface_protocol", "hardware_footprint",
                "data_locality", "agent_surface", "security_compliance")


def facet_counts(conn: sqlite3.Connection,
                 names: Iterable[str]) -> dict[str, list[dict]]:
    """Per-axis value counts over a candidate set. The drop-downs, as data.

    Computed from **the results**, never from the vocabulary. Searching
    *parser* should offer `ecosystem: Mixed (4), Web_Frontend (3)` and not the
    full fourteen-value enumeration with eleven zeroes - a facet listing values
    that cannot be selected is a menu of dead ends.

    Two properties fall out of decisions already made elsewhere, and both are
    the reason this belongs in the engine rather than in a page:

    - **A count is the size of the surviving set.** `eligible` removes
      candidates rather than demoting them, so choosing a value leaves exactly
      that many. The reader sees the cost of a constraint before paying it,
      which is the honest form of a filter.
    - **An axis that does not vary is omitted.** One value across every
      candidate narrows nothing, and saying so is a statement about coverage
      the ranked list cannot make.

    Returned to the MCP surface and the web app alike, so neither reimplements
    it and they cannot disagree.
    """
    rows = _facets(conn, names)
    if not rows:
        return {}
    out: dict[str, list[dict]] = {}
    for field in FACET_FIELDS:
        counts: dict[str, int] = {}
        for facet in rows.values():
            value = facet.get(field)
            if value in (None, ""):
                continue
            counts[str(value)] = counts.get(str(value), 0) + 1
        if len(counts) < 2:
            continue                    # an axis with one value narrows nothing
        out[field] = [{"value": value, "count": count}
                      for value, count in sorted(counts.items(),
                                                 key=lambda kv: (-kv[1], kv[0]))]
    return out


# ------------------------------------------------------- component retrieval

COMPONENT_LIMIT = 3

# A directory name in more than this share of surveyed sources says nothing
# about which source you want. `test`, `src` and `docs` are in almost all of
# them. Same reasoning as `SELECTIVITY_CEILING`, one grain down, and it ships
# with `component_name_distribution()` per `THRESHOLD_CARRIES_ITS_DISTRIBUTION`.
COMPONENT_SELECTIVITY_CEILING = 0.25


def find_components(terms: Sequence[str], limit: int = COMPONENT_LIMIT,
                    db_path: Path | None = None,
                    allowed_notes: Iterable[str] | None = None,
                    inherited: dict[str, dict[str, Any]] | None = None) -> list[Result]:
    """Addresses inside a source, not just the source.

    Every query until 2026-09-05 returned `kind: resource` - a whole repository -
    while the data layer held 2,761 directories and 4,877 component paths that
    no query could reach. The notes make the case against that themselves:
    `What Is Inside` exists because a source's most valuable content is
    routinely not what its abstract describes, and `elastic-labs` is catalogued
    for search while the thing worth opening is `example-apps/relevance-workbench`.

    So this returns the address. It reads the component store, never the vault,
    and it invents nothing: a component result exists only because a survey
    recorded that path at a known commit, which makes every one of them
    traceable in the sense [[Data Information Knowledge]] requires.

    **Capped deliberately.** Fine-grained results outnumber coarse ones by two
    orders of magnitude, so without a cap they would flood every answer. Three
    is enough to say *and look here specifically* and too few to bury the notes.

    **`allowed_notes` is not optional in practice.** The first version appended
    components *after* filtering, so a query constrained to `Permissive` came
    back with addresses inside sources the constraint had just eliminated. Nine
    existing tests failed at once and they were right to: *constraints
    eliminate* is the invariant this system is built on, and a component is
    part of the source it belongs to, not an exception to it.
    """
    from .components import connect
    from .config import component_db_path

    target = Path(db_path or component_db_path())
    if not target.exists() or not terms:
        return []
    wanted = [t.lower() for t in terms if len(t) > 3]
    if not wanted:
        return []

    conn = connect(target)
    try:
        scored: dict[tuple[str, str], dict[str, Any]] = {}

        def add(repo_key: str, address: str, kind: str, term: str,
                detail: str) -> None:
            key = (repo_key, address)
            row = scored.setdefault(key, {"repo_key": repo_key, "address": address,
                                          "kind": kind, "terms": set(),
                                          "detail": detail})
            row["terms"].add(term)

        total = conn.execute("SELECT COUNT(*) FROM source").fetchone()[0] or 1

        def selective(term: str) -> bool:
            """Does this term pick out a source, or is it in most of them?

            `test` is a directory in nearly every surveyed repository, so
            matching it names no source in particular. Measured, not listed -
            a stoplist here would need maintaining and would still miss the
            next ubiquitous name.
            """
            row = conn.execute(
                "SELECT COUNT(DISTINCT repo_key) n FROM directory "
                "WHERE lower(name) = ?", (term,)).fetchone()
            return (row["n"] or 0) / total < COMPONENT_SELECTIVITY_CEILING

        for term in wanted:
            if not selective(term):
                continue
            like = f"%{term}%"
            for row in conn.execute(
                    "SELECT repo_key, parent, name, files FROM directory "
                    "WHERE name LIKE ? ORDER BY files DESC LIMIT 24", (like,)):
                # Whole-segment matching. `LIKE '%side%'` returns `sidekiq` and
                # `SideNav`, which is the substring defect this system already
                # fixed once for `interface_protocol: "REST"` matching *the rest
                # of the system* - and which `F:\Mark-XLVIII-main` documents
                # fixing independently in its own capability search.
                if not _matched_terms_bounded(row["name"], [term]):
                    continue
                address = (f"{row['parent']}/{row['name']}" if row["parent"]
                           else row["name"])
                add(row["repo_key"], address, "directory", term,
                    f"{row['files']} files")
            for table, detail in (("path", ""), ("signal_path", "sampled")):
                column = "path"
                for row in conn.execute(
                        f"SELECT repo_key, {column} FROM {table} "
                        f"WHERE {column} LIKE ? LIMIT 24", (like,)):
                    segments = row[column].replace("/", " ").replace(".", " ")
                    if not _matched_terms_bounded(segments, [term]):
                        continue
                    add(row["repo_key"], row[column], "file", term, detail)

        notes = {r["repo_key"]: r["note"] for r in
                 conn.execute("SELECT repo_key, note FROM source")}
    except sqlite3.OperationalError:
        # No component store, or one built by an older schema. Same posture as
        # LM Studio, graphify and the toolchain: return nothing and let the
        # caller carry on, never raise into a query.
        return []
    finally:
        conn.close()

    inherited = inherited or {}
    if allowed_notes is not None:
        permitted = set(allowed_notes)
        scored = {key: row for key, row in scored.items()
                  if notes.get(row["repo_key"]) in permitted}

    ranked = sorted(scored.values(), key=lambda r: (-len(r["terms"]),
                                                    len(r["address"])))
    out: list[Result] = []
    for row in ranked[:limit]:
        matched = sorted(row["terms"])
        why = ("matched " + ", ".join(f"'{m}'" for m in matched[:3])
               + f" in a {row['kind']} recorded by the survey of "
                 f"{row['repo_key']}")
        if row["detail"]:
            why += f" ({row['detail']})"
        note_name = notes.get(row["repo_key"]) or ""
        fields = {"repo_key": row["repo_key"], "address": row["address"],
                  "component_kind": row["kind"], "matched": matched,
                  "note": note_name}
        # Inherit the source's taxonomy. A component *is* filtered - it is only
        # offered when its note survived - but without these fields it looks
        # unfiltered, and a cold agent reading `license_class: None` on a row
        # returned under `license_class=Permissive` reasonably concluded the
        # constraint had been bypassed. A constraint you cannot verify held is
        # one a caller must assume did not.
        fields.update(inherited.get(note_name) or {})
        out.append(Result(
            "component", f"{row['repo_key']} > {row['address']}", why, 0.55,
            fields))
    return out


def component_name_distribution(db_path: Path | None = None) -> dict[str, Any]:
    """How common directory names are, so the ceiling is derived not guessed.

    `THRESHOLD_CARRIES_ITS_DISTRIBUTION`. Run after a large intake; a share
    fixed against a corpus that has doubled is not a threshold.
    """
    from .components import connect
    from .config import component_db_path

    target = Path(db_path or component_db_path())
    if not target.exists():
        return {}
    conn = connect(target)
    try:
        total = conn.execute("SELECT COUNT(*) FROM source").fetchone()[0] or 1
        rows = conn.execute(
            "SELECT lower(name) name, COUNT(DISTINCT repo_key) n FROM directory "
            "GROUP BY 1 ORDER BY 2 DESC LIMIT 15").fetchall()
        return {"sources": total, "ceiling": COMPONENT_SELECTIVITY_CEILING,
                "most_common": [(r["name"], round(r["n"] / total, 3)) for r in rows]}
    finally:
        conn.close()

def _why(hit: Hit | None, filters: str, extra: str = "") -> str:
    """Assembled from evidence, never written by a model."""
    parts: list[str] = []
    if hit and hit.matched:
        if hit.heading == "name":
            where = " in the note name"
        elif hit.heading == "frontmatter":
            where = " in the frontmatter"
        elif hit.heading:
            where = f" in ## {hit.heading}"
        else:
            where = ""
        parts.append("matched " + ", ".join(f"'{t}'" for t in hit.matched[:4]) + where)
    else:
        # Reached by vector similarity alone. Saying so is the honest
        # explanation; naming a term that did not match would not be.
        parts.append("closest by meaning; no exact term matched")
    if extra:
        parts.append(extra)
    if filters:
        parts.append(f"passed filters: {filters}")
    return "; ".join(parts) or "matched the query"


def _proven_use_bonus(facet: dict | None) -> tuple[float, str]:
    """A resource with a recorded successful use outranks a plausible stranger.

    Log-dampened for the same reason star counts are: one loud record must not
    bury a better-fitting resource nobody has written up yet.
    """
    count = int((facet or {}).get("application_count") or 0)
    if count <= 0:
        return 0.0, ""
    import math
    return min(0.15, 0.08 * math.log1p(count)), f"used in {count} application record(s)"


