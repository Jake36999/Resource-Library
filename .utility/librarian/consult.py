# Sections that assert what a source *does*, as against sections that record
# what is true *about* it. The distinction decides whether a term match is
# evidence for the source or merely evidence that the word appears in its note.
CLAIM_SECTIONS = frozenset({
    "bottom line", "what it solves", "architecture & mechanics",
    "what is inside", "transferable capability", "integration & use cases",
    "taxonomy", "definition", "why it matters", "inclusion criteria",
    "canonical vocabulary", "why this topic exists", "mechanics",
    "typical use cases", "what was needed", "what was found and taken",
    "what it replaced", "what the catalogue should learn", "name",
})

# Everything else a note carries: provenance, limits, corrections, links.
CAVEAT_SECTIONS = frozenset({"reading notes", "evidence", "sense notes",
                             "observed contexts", "frontmatter"})


def is_claim_section(heading: str) -> bool:
    """True when a match here is evidence the source does the thing.

    Unknown headings count as claims. A new section is more likely to describe
    a source than to caveat it, and the failure this guards against is the
    specific one where a caveat is read as a claim.
    """
    return (heading or "name").strip().lower() not in CAVEAT_SECTIONS


SELECTIVITY_CEILING = 0.50      # a term in most of the corpus cannot discriminate


ANSWERABLE_LAYERS = ("resource", "review", "paper")


def _selective_terms(conn: sqlite3.Connection, terms: Sequence[str],
                     ceiling: float | None = None,
                     scope: str = "answerable") -> frozenset[str]:
    """Which query terms are discriminating enough to count as coverage.

    Measured, not assumed: a term is selective when fewer than
    `SELECTIVITY_CEILING` of notes contain it. This is document frequency doing
    the job a stopword list does badly - `over` and `work` pass any reasonable
    stoplist and still carry no information about which note is wanted.

    **Two things make this statistic easy to get wrong, and both were.**

    *The denominator.* Document frequency was measured over every note in the
    vault. Only `resource`, `review` and `paper` notes can ever be an answer,
    and the other 211 - glossary, patterns, topics, this system's own design
    documents - are short and dilute the count. Measured over the notes that
    can actually be returned, `read` is in 96% of them, `file` 93%, `files`
    86%, `test` 73%: useless discriminators that the wrong denominator scored
    at 0.53, 0.48, 0.38 and 0.39 and waved through. `scope="answerable"` is
    the default from 2026-09-04.

    *The corpus moves.* A fixed share is a moving target - the 2026-09-04
    cohort took the vault from 81 resources to 128 - and so is the vault's own
    documentation. An earlier note here claimed raising the ceiling from 0.34
    to 0.50 recovered a scenario outright. **It did, and then it did not.**
    Re-measured after five index notes were edited, 0.34 and 0.50 are
    indistinguishable on `useful@5`. The gain was real and it was not the
    ceiling; it was the corpus. That is why `librarian relevance` exists and
    why nothing here should be settled by editing a constant and re-running.

    0.50 is kept because *a term in more than half the answerable corpus
    cannot discriminate* is a threshold with a reason, and because the grid in
    `rank_configs.json` puts it at the top jointly with `coverage_order=bm25`.

    **What was tried and rejected**: weighting the surviving terms by inverse
    document frequency (`coverage_order="idf"`, still selectable). It loses at
    every ceiling. IDF is computed over the corpus, so it scores `scope` (df
    0.05) and `want` (0.08) far above `file` - and those are artefacts of how a
    query is phrased, not signal. Document frequency cannot separate "rare and
    meaningful" from "rare and incidental".

    `config-validation-surface` fails under every configuration in the grid and
    neither knob is its cause. Its description names a storage engine and a
    query layer as explicitly *out of scope*, and those terms drive the result;
    the ask and the context are not distinguished. That one is open.
    """
    if not terms:
        return frozenset()
    bar = SELECTIVITY_CEILING if ceiling is None else ceiling
    if scope == "all":
        total = conn.execute("SELECT COUNT(*) AS n FROM note").fetchone()["n"] or 1
        count = ("SELECT COUNT(DISTINCT note) AS n FROM chunk WHERE text LIKE ?", ())
    else:
        marks = ",".join("?" for _ in ANSWERABLE_LAYERS)
        total = conn.execute(
            f"SELECT COUNT(*) AS n FROM note WHERE layer IN ({marks})",
            ANSWERABLE_LAYERS).fetchone()["n"] or 1
        count = (f"SELECT COUNT(DISTINCT c.note) AS n FROM chunk c "
                 f"JOIN note nt ON nt.name = c.note "
                 f"WHERE c.text LIKE ? AND nt.layer IN ({marks})", ANSWERABLE_LAYERS)
    keep: set[str] = set()
    for term in terms:
        row = conn.execute(count[0], (f"%{term}%", *count[1])).fetchone()
        if (row["n"] or 0) / total < bar:
            keep.add(term.lower())
    return frozenset(keep)



def _coverage_key(conn: sqlite3.Connection, order: str,
                  selective: frozenset[str], query: str = ""):
    """The sort key for covered notes, chosen by `CatalogueConfig.coverage_order`.

    `terms` was the only behaviour until 2026-09-04 and remains the default:
    more matched terms ranks higher, ties broken by the text ranking's own
    position. `bm25` reverses that priority, letting the score FTS5 already
    computed decide and using the term count only to break ties - which is
    worth being able to test, because a count treats `service` and `malformed`
    as equally decisive and BM25 does not. `idf` is retained as a control.
    """
    if order == "segment":
        # Weight a matched term by the role it played in the request: full for
        # the ask, `CONTEXT_WEIGHT` for surrounding description, zero for a
        # clause that ruled it out. Deleting excluded terms outright was
        # measured first and was worse - it shrinks the evidence base until
        # single-term matches win. Weighting keeps the evidence and reorders it.
        from .queryunderstanding import segment

        seg = segment(query)
        return lambda h: (-sum(seg.weight_of(t) for t in h.matched), h.rank)
    if order == "bm25":
        return lambda h: (h.rank, -len(h.matched))
    if order == "idf":
        weights = _term_idf(conn, selective)
        return lambda h: (-sum(weights.get(t.lower(), 0.0) for t in h.matched), h.rank)
    return lambda h: (-len(h.matched), h.rank)


def _term_idf(conn: sqlite3.Connection,
              terms: Iterable[str]) -> dict[str, float]:
    """Inverse document frequency over the note index.

    Only `coverage_order="idf"` uses this, and that setting loses. It is kept
    because a rejected option nobody can re-run is a claim rather than a
    finding - see `_selective_terms` for what was measured and why it failed.
    """
    total = conn.execute("SELECT COUNT(*) AS n FROM note").fetchone()["n"] or 1
    out: dict[str, float] = {}
    for term in terms:
        row = conn.execute(
            "SELECT COUNT(DISTINCT note) AS n FROM chunk WHERE text LIKE ?",
            (f"%{term}%",)).fetchone()
        share = (row["n"] or 0) / total
        out[term.lower()] = math.log(1.0 / share) if share > 0 else 0.0
    return out

def selectivity_distribution(terms: Sequence[str] | None = None,
                             db_path: Path | None = None,
                             cfg: CatalogueConfig | None = None) -> dict[str, Any]:
    """The document-frequency spread the ceiling is a cut through.

    `THRESHOLD_CARRIES_ITS_DISTRIBUTION`. This one is the reason the invariant
    exists: 0.34 was right at 81 resources and wrong at 128, and the change was
    found by a scenario regression rather than by anyone checking.

    With no `terms`, samples the vocabulary of the corpus itself, which is the
    right basis - a query term only matters relative to how common it is here.
    """
    import sqlite3

    cfg = cfg or CatalogueConfig.load()
    conn = sqlite3.connect(str(db_path or index_db_path()))
    conn.row_factory = sqlite3.Row
    try:
        if terms is None:
            rows = conn.execute(
                "SELECT text FROM chunk WHERE layer IN "
                f"({','.join('?' for _ in ANSWERABLE_LAYERS)}) LIMIT 400",
                ANSWERABLE_LAYERS).fetchall()
            counter: dict[str, int] = {}
            for row in rows:
                for word in set(terms_from(row["text"] or "")):
                    counter[word.lower()] = counter.get(word.lower(), 0) + 1
            terms = [w for w, _ in sorted(counter.items(),
                                          key=lambda kv: -kv[1])[:120]]
        marks = ",".join("?" for _ in ANSWERABLE_LAYERS)
        total = conn.execute(
            f"SELECT COUNT(*) AS n FROM note WHERE layer IN ({marks})",
            ANSWERABLE_LAYERS).fetchone()["n"] or 1
        shares = []
        for term in terms:
            row = conn.execute(
                f"SELECT COUNT(DISTINCT c.note) AS n FROM chunk c "
                f"JOIN note nt ON nt.name = c.note "
                f"WHERE c.text LIKE ? AND nt.layer IN ({marks})",
                (f"%{term}%", *ANSWERABLE_LAYERS)).fetchone()
            shares.append(((row["n"] or 0) / total, term))
    finally:
        conn.close()
    shares.sort()
    if not shares:
        return {}
    ceiling = cfg.selectivity_ceiling
    return {
        "answerable_notes": total,
        "terms_sampled": len(shares),
        "ceiling": ceiling,
        "median_share": round(shares[len(shares) // 2][0], 3),
        "eliminated": sum(1 for share, _ in shares if share >= ceiling),
        "kept": sum(1 for share, _ in shares if share < ceiling),
        "closest_below": [t for s, t in shares if s < ceiling][-5:],
        "closest_above": [t for s, t in shares if s >= ceiling][:5],
    }


def _search(conn: sqlite3.Connection, query: str, cfg: CatalogueConfig,
            layers: Sequence[str] | None, pool: int = 60
            ) -> tuple[dict[str, float], dict[str, Hit], list[str], int]:
    """Filters -> lexical -> vectors -> RRF. Returns scores, best hit per note,
    degradation notes, and the deepest tier consulted."""
    terms = terms_from(query)
    if cfg.query_segmentation:
        # Terms a request names in order to rule them out are not the request.
        # See `queryunderstanding`; measured through `librarian relevance`
        # rather than assumed, because a segmenter fitted to one author's
        # phrasing produces a number and no capability.
        from .queryunderstanding import segment

        excluded = set(segment(query).excluded)
        if excluded:
            kept = [t for t in terms if t.lower() not in excluded]
            if kept:                     # never leave a query with nothing
                terms = kept
    name_hits = by_name(conn, terms, layers)
    text_hits = lexical(conn, terms, layers, limit=pool)

    best: dict[str, Hit] = {}
    for hit in name_hits + text_hits:
        current = best.get(hit.note)
        if current is None or hit.rank < current.rank:
            best[hit.note] = hit

    # A third contributor: how much of the query each note actually matched.
    #
    # RRF fuses *positions*, not strengths, so a note ranked first in the
    # lexical list on one common term outranks one ranked second on four. That
    # is how `neo4j-labs - neocarta` (matching 'database') came to beat
    # `osquery - osquery` (matching 'operating', 'system', 'database') for
    # "query the operating system state as if it were a database".
    #
    # Coverage needs no calibration - it is a count of distinct query terms
    # already computed for the `why` string - so it enters as another ranking
    # rather than as a score multiplier, which keeps every contributor
    # inspectable and keeps RRF doing the only job it is good at.
    # ...but only where the match is a *claim*. A note's sections do different
    # jobs: some assert what the source does, others record what is wrong with
    # it. `Reading Notes` on `shenhuan2021 - gudu-sql-omni-introduce` contains
    # 'SQL', 'transformations' and 'lineage' inside the sentence "It is not
    # that" - a caveat quoting the description it exists to refute. Counting
    # that as evidence the source does the thing put it above `dbt-core`.
    #
    # Caveats stay searchable, because "which sources are abandoned" is a real
    # question. They simply do not earn coverage credit.
    # Count only terms that actually discriminate. `over`, `work` and `no`
    # survive the stopword list but appear in most of the vault, so counting
    # them lets a note match four words of a query while sharing nothing
    # specific with it. Selectivity is measured from the index rather than
    # guessed: a term in more than a third of notes carries no information
    # about which note you want.
    selective = _selective_terms(conn, terms, cfg.selectivity_ceiling,
                                 cfg.selectivity_scope)

    # Narrow every hit to the terms that actually counted, before anything reads
    # them. `hit.matched` is what the `why` string reports, so leaving the
    # discarded terms on it would have the explanation claim evidence the
    # ranking refused to use - 'each' and 'one' presented as reasons.
    def only_counted(hits: list[Hit]) -> list[Hit]:
        return [Hit(h.note, h.layer, h.heading, h.excerpt,
                    tuple(t for t in h.matched if t.lower() in selective), h.rank)
                for h in hits]

    text_hits = only_counted(text_hits)
    name_hits = only_counted(name_hits)
    best = {}
    for hit in name_hits + text_hits:
        current = best.get(hit.note)
        if current is None or hit.rank < current.rank:
            best[hit.note] = hit

    by_note: dict[str, Hit] = {}
    for hit in text_hits + name_hits:
        if not is_claim_section(hit.heading):
            continue
        current = by_note.get(hit.note)
        if current is None or len(hit.matched) > len(current.matched):
            by_note[hit.note] = hit
    # How a covered note is ordered is a stage, not a constant. `terms` counts
    # matched terms equally; `bm25` defers to the score the text ranking
    # already trusts, which has term saturation and length normalisation that a
    # count does not; `idf` is the naive weighting that was measured and lost,
    # kept selectable so the rejection stays reproducible rather than folklore.
    covered = sorted(by_note.values(),
                     key=_coverage_key(conn, cfg.coverage_order, selective, query))
    coverage = [h.note for h in covered
                if len(h.matched) >= cfg.coverage_min_terms]

    # One entry per note, keeping its best-placed chunk.
    #
    # RRF is defined over rankings of distinct items. `lexical` returns a
    # *chunk* ranking, so a note appears once per matching section and `rrf`
    # sums each appearance - which quietly turns "how many of my sections
    # mention this" into a ranking signal. It rewards verbose notes, and it got
    # worse every time a section was added to the schema: it is why
    # `shenhuan2021 - gudu-sql-omni-introduce`, whose four sections all discuss
    # SQL lineage, outranked `dbt-labs - dbt-core`, which does it.
    def first_per_note(hits: list[Hit]) -> list[str]:
        seen: set[str] = set()
        out: list[str] = []
        for hit in hits:
            if hit.note not in seen:
                seen.add(hit.note)
                out.append(hit.note)
        return out

    rankings = [first_per_note(name_hits), first_per_note(text_hits), coverage]
    weights = [cfg.lexical_weight * cfg.name_weight_multiplier,
               cfg.lexical_weight,
               cfg.lexical_weight * cfg.coverage_weight_multiplier]
    degraded: list[str] = []
    tier = 1 if not text_hits else 3

    if cfg.embeddings_enabled:
        vector_hits, reason = embed_mod.search(conn, query, cfg, limit=pool, layers=layers)
        if reason:
            degraded.append(reason)
        else:
            ordered: list[str] = []
            for _, note_name, score in vector_hits:
                if note_name not in ordered:
                    ordered.append(note_name)
                    best.setdefault(note_name, Hit(
                        note=note_name, layer="", heading="",
                        excerpt="", matched=(), rank=len(ordered)))
            rankings.append(ordered)
            weights.append(cfg.vector_weight)
            if ordered:
                tier = 3

    return _normalise(rrf(rankings, cfg.rrf_k, weights)), best, degraded, tier


def _facets(conn: sqlite3.Connection, names: Iterable[str]) -> dict[str, dict]:
    names = list(names)
    if not names:
        return {}
    marks = ",".join("?" for _ in names)
    rows = conn.execute(
        f"SELECT * FROM resource_facet WHERE name IN ({marks})", names).fetchall()
    return {row["name"]: dict(row) for row in rows}



