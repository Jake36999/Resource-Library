def _communities_touching(conn: sqlite3.Connection, names: set[str],
                          limit: int = 2) -> list[Result]:
    """Community reports whose members include something already matched.

    Only the ones that *cross topics* are offered. A community confined to one
    topic mostly restates that topic, and the topic index is the better answer
    for it; a community spanning several is the finding, because nobody
    assigned it.
    """
    if not names:
        return []
    try:
        rows = conn.execute(
            "SELECT community, label, size, topics, summary, members "
            "FROM community_report ORDER BY size DESC").fetchall()
    except sqlite3.OperationalError:          # index predates the table
        return []
    out: list[Result] = []
    for row in rows:
        try:
            members = set(json.loads(row["members"] or "[]"))
            topics = json.loads(row["topics"] or "{}")
        except ValueError:                    # pragma: no cover
            continue
        overlap = members & names
        if not overlap or len([t for t in topics if t]) < 2:
            continue
        out.append(Result(
            "community", f"Community {row['community']}",
            f"a grouping the vault graph found, containing {', '.join(sorted(overlap)[:2])}; "
            f"spans {len(topics)} topics",
            0.30,
            {"size": row["size"], "topics": topics, "summary": row["summary"],
             "members": sorted(members)}))
        if len(out) >= limit:
            break
    return out


def orient(topic_or_keywords: str, limit: int = 10, *, db_path: Path | None = None,
           cfg: CatalogueConfig | None = None) -> Response:
    """R1 - what is here, and where does this subject live?"""
    cfg = cfg or CatalogueConfig.load()
    conn = _conn(db_path)
    try:
        scores, best, degraded, _ = _search(conn, topic_or_keywords, cfg,
                                            layers=None, pool=80)
        results: list[Result] = []

        topics = _top(scores, best, ("topic",), conn, limit=min(limit, 5))
        for name, score, hit in topics:
            results.append(Result("topic", name, _why(hit, ""), score,
                                  _topic_fields(conn, name)))

        # Resources under a matched topic come first: the topic answered the
        # question, so its members are the answer's contents rather than a
        # separate lexical guess.
        under: list[str] = []
        for name, _, _ in topics:
            under.extend(_children_of(conn, name))
        facets = _facets(conn, set(under) | set(scores))

        resources = _top(scores, best, ("resource", "review", "paper"), conn, limit=limit)
        seen = {name for name, _, _ in resources}
        for name in under:
            if name not in seen and len(resources) < limit:
                resources.append((name, 0.35, None))
                seen.add(name)

        for name, score, hit in resources:
            facet = facets.get(name, {})
            kind = "aggregator" if facet.get("is_container") else "resource"
            extra = ""
            if hit is None:
                parent = _parent_topic(conn, name)
                extra = f"listed under {parent}" if parent else "in the matched topic"
            results.append(Result(kind, name, _why(hit, "", extra), score,
                                  _resource_fields(facet)))

        # A community the graph found, containing something already matched.
        # `orient` is the "what is this area" query, so a grouping nobody
        # assigned belongs in its answer - and a report is the only artefact
        # that can say what the catalogue has *become* rather than what somebody
        # filed. Read from the index, never computed here (spec 4B R6), and
        # advisory: it names a shape, it does not reassign anything (R3).
        matched = {r.name for r in results}
        for community in _communities_touching(conn, matched):
            results.append(community)

        aggregators = [r for r in results if r.kind == "aggregator"]
        return Response(
            intent="orient",
            results=tuple(results),
            tier_reached=3 if any(h for _, _, h in resources) else 2,
            next_step=(f"open the topic index for a full listing, or call find_donor "
                       f"with your constraints to narrow {len(results)} candidates"
                       if results else
                       "nothing matched; try broader keywords, or check the domain "
                       "register for whether this subject is in scope yet"),
            partial=bool(degraded),
            notes=tuple(degraded) + ((f"{len(aggregators)} of these are aggregators - "
                                      "lists of resources rather than resources",)
                                     if aggregators else ()),
        )
    finally:
        conn.close()


def find_donor(need: str, constraints: dict | Constraints | None = None,
               limit: int = 10, *, db_path: Path | None = None,
               cfg: CatalogueConfig | None = None) -> Response:
    """R2 - what could I take, given what I can actually run?"""
    cfg = cfg or CatalogueConfig.load()
    bounds = Constraints.of(constraints)
    conn = _conn(db_path)
    try:
        scores, best, degraded, tier = _search(conn, need, cfg,
                                               layers=("resource", "review", "paper"),
                                               pool=80)
        survivors, eliminated, described = eligible(conn, bounds)
        total_pool = len(survivors) + eliminated
        # Filters eliminate before ranking. A candidate that fails a
        # constraint is absent, not demoted.
        kept = {name: score for name, score in scores.items() if name in survivors}

        # Which of the *best* candidates the constraints removed. Silently
        # dropping the top hit and returning the next thing is how a caller ends
        # up reusing a Markdown parser for SQL: the honest answer to "parse SQL,
        # permissive only" may be that the only SQL parser here is copyleft, and
        # the response has to be able to say so.
        removed_best = [name for name, _ in
                        sorted(scores.items(), key=lambda kv: -kv[1])[:3]
                        if name not in survivors]

        # Structured filters are usable with no search machinery at all
        # (spec 3.2, stage 1). When nothing matched lexically but the
        # constraints are real, list what survives rather than nothing:
        # "everything permissive that runs on a server" is a valid question.
        filters_only = not kept and survivors and bounds.active()
        if filters_only:
            kept = {name: 0.5 for name in survivors}
        facets = _facets(conn, kept)

        ordered = sorted(kept.items(),
                         key=lambda kv: (-kv[1], -(facets.get(kv[0], {}).get("stars") or 0))
                         if filters_only else -kv[1])
        ranked: list[Result] = []
        for name, score in ordered[:limit]:
            facet = facets.get(name, {})
            bonus, bonus_why = _proven_use_bonus(facet)
            extra = bonus_why
            if filters_only:
                extra = "; ".join(x for x in (
                    "no term matched; listed because it survives the constraints",
                    bonus_why) if x)
            hit = best.get(name)
            fields = _resource_fields(facet)
            # The terms that actually matched, structurally rather than inside
            # the `why` sentence. `coverage.assess` needs them, and a caller
            # deciding whether to trust an answer should not have to parse prose.
            fields["matched"] = list(hit.matched) if hit else []
            fields["matched_in"] = hit.heading if hit else ""
            ranked.append(Result(
                "resource", name, _why(hit, described, extra),
                min(1.0, score + bonus), fields))
        ranked.sort(key=lambda r: -r.score)

        # Over `kept`, not over `ranked`: a shop counts every match and shows
        # you the first page. Facets computed from five results would narrow
        # nothing and would misreport what choosing a value costs.
        available = facet_counts(conn, kept)

        # A different grain, returned in a different field. Mixing them into
        # `results` made `limit` ambiguous - `limit=3` returned four rows - and
        # left a caller to notice the change of kind for themselves. `limit`
        # now means *sources*, because that is what somebody asking for five
        # candidates means, and components are supplementary detail about those
        # sources rather than competitors to them.
        #
        # Restricted to sources that survived the filters: a component of an
        # eliminated source is still eliminated.
        components: tuple[Result, ...] = ()
        if cfg.include_components and kept:
            components = tuple(find_components(
                terms_from(need), allowed_notes=set(kept),
                inherited={n: _resource_fields(facets.get(n, {}))
                           for n in kept}))

        # Two things the caller cannot see from a ranked list, and which decide
        # whether it should act on one: did a constraint remove a better answer,
        # and is this response worth trusting at all.
        advisories: list[str] = []
        if removed_best and bounds.active():
            advisories.append(
                f"{len(removed_best)} of the highest-scoring candidates were "
                f"removed by your constraints ({described}): "
                f"{', '.join(removed_best)}. If none of the results below fits, "
                f"the honest answer may be that the catalogue holds no match "
                f"under those constraints rather than the one it returned.")

        from .coverage import assess as _assess
        verdict = _assess(need, Response(intent="donor", results=tuple(ranked)),
                          db_path=db_path, cfg=cfg)
        if verdict.level != "covered":
            advisories.append(verdict.sentence())

        if ranked and verdict.level == "uncovered":
            next_step = ("nothing here covers this. Treat the results below as "
                         "the nearest material rather than as answers, and "
                         "record the gap.")
        elif ranked:
            next_step = (f"read the Bottom Line of the top {min(3, len(ranked))}, then "
                         f"open a workbench on the one you choose - the catalogue "
                         f"locates donors, it does not extract them")
        elif eliminated:
            next_step = (f"every candidate failed a constraint ({described}); relax one "
                         f"or record the gap - {eliminated} were eliminated")
        else:
            next_step = "nothing matched; try the vocabulary the domain itself uses"

        return Response(intent="donor", results=tuple(ranked),
                        components=components,
                        facets=available, matched=len(kept),
                        considered=total_pool,
                        filtered_out=eliminated, advisories=tuple(advisories),
                        tier_reached=2 if (filters_only or not ranked) else tier,
                        next_step=next_step,
                        partial=bool(degraded), notes=tuple(degraded))
    finally:
        conn.close()


def find_pattern(problem: str, limit: int = 5, *, db_path: Path | None = None,
                 cfg: CatalogueConfig | None = None) -> Response:
    """R3 - has this shape of problem been solved before, and by what?"""
    cfg = cfg or CatalogueConfig.load()
    conn = _conn(db_path)
    try:
        scores, best, degraded, tier = _search(conn, problem, cfg,
                                               layers=("pattern",), pool=40)
        patterns = _top(scores, best, ("pattern",), conn, limit=limit)
        results: list[Result] = []
        for name, score, hit in patterns:
            results.append(Result("pattern", name, _why(hit, ""), score,
                                  _pattern_fields(conn, name)))

        # Examples and neighbours come from the link graph, which is already
        # in the notes - no separate traversal store is needed for this.
        if patterns:
            head = patterns[0][0]
            for example in _incoming(conn, head, "implements_pattern"):
                results.append(Result(
                    "resource", example,
                    f"implements_pattern -> {head}", 0.6,
                    _resource_fields(_facets(conn, [example]).get(example, {}))))
            for related in _related_patterns(conn, head):
                results.append(Result("pattern", related,
                                      f"shares a topic or link with {head}", 0.4,
                                      _pattern_fields(conn, related)))

        return Response(
            intent="pattern", results=tuple(results), tier_reached=tier if results else 1,
            next_step=("read the pattern, then compare the example implementations - "
                       "they solve the same shape differently"
                       if results else
                       "no pattern matched; if the shape recurs, it is worth writing one"),
            partial=bool(degraded), notes=tuple(degraded))
    finally:
        conn.close()


def find_technique(what: str, source: str | None = None, limit: int = 10, *,
                   db_path: Path | None = None,
                   cfg: CatalogueConfig | None = None) -> Response:
    """R4 - where would I look to see how this is done?

    A locator, not an extractor. This query ends at tier 3 and says so: the
    technique itself lives in the source, and reaching it means opening a
    workbench, which is a person's decision. Nothing here fetches, clones or
    slices - the read path stays fast and side-effect free, which is what
    makes it safe to expose to third-party agents.
    """
    cfg = cfg or CatalogueConfig.load()
    conn = _conn(db_path)
    try:
        layers = ("resource", "review", "paper", "application", "pattern")
        scores, best, degraded, tier = _search(conn, what, cfg, layers=layers, pool=80)

        note_for_source = None
        if source:
            note_for_source = _note_for_source(conn, source)
            if note_for_source is None:
                return Response(
                    intent="technique", results=(), tier_reached=1,
                    next_step=(f"'{source}' is not catalogued. Add it through the intake "
                               f"(`python -m scout` directed mode) before asking where "
                               f"inside it to look."),
                    notes=("refused: the consult surface never fetches a source; "
                           "cataloguing is an intake operation subject to intake gates",))
            scores = {k: v for k, v in scores.items() if k == note_for_source}
            if note_for_source not in scores:
                scores[note_for_source] = 0.5

        facets = _facets(conn, scores)
        sources: list[Result] = []
        evidence: list[Result] = []
        for name, score in sorted(scores.items(), key=lambda kv: -kv[1]):
            hit = best.get(name)
            facet = facets.get(name)
            fields = _resource_fields(facet)
            if hit:
                fields["evidence"] = hit.excerpt
                fields["evidence_section"] = hit.heading
            if facet:
                if len(sources) < limit:
                    sources.append(Result(
                        "resource", name,
                        _why(hit, "", "described as relevant to the technique"),
                        score, fields))
            elif not is_hub(_note_type(conn, name)) and len(evidence) < 3:
                # A pattern or an application record does not contain the
                # technique, but it says who does - so it is returned as
                # supporting evidence, not as somewhere to go and look.
                evidence.append(Result(
                    "note", name, _why(hit, "", "context that points at a source"),
                    score * 0.5, fields))

        results = sources + evidence
        head = sources[0] if sources else None
        repo = (head.fields.get("repo_key") or head.name) if head else ""
        return Response(
            intent="technique", results=tuple(results), tier_reached=3 if results else 1,
            next_step=(f"open a workbench on {repo} to confirm - the catalogue records "
                       f"where a technique is likely to live, not the technique itself"
                       if head else
                       "nothing described this technique; the catalogue cannot say where "
                       "to look, which is a gap worth recording"),
            partial=bool(degraded),
            notes=tuple(degraded) + (
                "slices are ephemeral by design: no permanent index of extracted "
                "symbols exists, so this answer ends at the source, not inside it",))
    finally:
        conn.close()


def find_data(subject: str, purpose: str | None = None, limit: int = 10, *,
              db_path: Path | None = None,
              cfg: CatalogueConfig | None = None) -> Response:
    """R5 - what data exists for this, and how do I reach it?

    Returns datasets, the access points that address them, and any validation
    criteria a real application record has already established. The third of
    those is the need [[Application - Quantum Simulation Project]] identified:
    a maturing project needs data and validation points, not more method.
    """
    cfg = cfg or CatalogueConfig.load()
    query = f"{subject} {purpose or ''}".strip()
    conn = _conn(db_path)
    try:
        scores, best, degraded, tier = _search(
            conn, query, cfg, layers=("resource", "review", "paper", "application"),
            pool=80)
        facets = _facets(conn, scores)

        results: list[Result] = []
        eliminated = 0
        with_addresses = _sources_with_access_points(conn)
        for name, score in sorted(scores.items(), key=lambda kv: -kv[1]):
            facet = facets.get(name)
            if facet is None:
                continue
            # A recorded address is the strongest evidence that a source
            # serves data, and it outranks any taxonomy guess about it.
            data_shaped = (facet.get("domain_primary") in DATASET_DOMAINS
                           or _note_type(conn, name) in DATASET_TYPES
                           or facet.get("interface_protocol") in {"REST", "GraphQL"}
                           or name in with_addresses
                           or (facet.get("repo_key") or "") in with_addresses)
            if not data_shaped:
                eliminated += 1
                continue
            if len(results) >= limit:
                continue
            results.append(Result(
                "dataset", name,
                _why(best.get(name), "",
                     f"data-shaped: domain {facet.get('domain_primary')}, "
                     f"protocol {facet.get('interface_protocol')}"),
                score, _resource_fields(facet)))

        dataset_names = [r.name for r in results]
        for row in _access_points_for(conn, dataset_names):
            results.append(Result(
                "access_point", row["id"],
                f"address recorded for {row['source']}"
                + (f", verified {row['verified_at']}" if row["verified_at"] else
                   ", never verified"),
                0.5,
                {"source": row["source"], "kind": row["kind"], "url": row["url"],
                 "auth": row["auth"], "rate_limit": row["rate_limit"],
                 "formats": json.loads(row["formats"] or "[]"),
                 "verified_at": row["verified_at"],
                 "reachable": row["reachable"]}))

        for name, criterion in _validation_criteria(conn, dataset_names):
            results.append(Result("criterion", criterion,
                                  f"recorded in {name}", 0.4, {"source_record": name}))

        return Response(
            intent="data", results=tuple(results), filtered_out=eliminated,
            tier_reached=tier if results else 2,
            next_step=("check each access point's verified_at before depending on it; "
                       "an address recorded a year ago is a hypothesis"
                       if any(r.kind == "access_point" for r in results) else
                       "no access points are recorded for these; the intake extracts "
                       "them during scouting, so this is a gap rather than an absence"),
            partial=bool(degraded), notes=tuple(degraded))
    finally:
        conn.close()


def find_precedent(resource_or_topic: str, limit: int = 10, *,
                   db_path: Path | None = None,
                   cfg: CatalogueConfig | None = None) -> Response:
    """R6 - has this been used before, and what happened?"""
    cfg = cfg or CatalogueConfig.load()
    conn = _conn(db_path)
    try:
        target = _resolve_note(conn, resource_or_topic)
        results: list[Result] = []
        seen: set[str] = set()

        if target:
            for src, relation in _incoming_any(conn, target):
                if _layer(conn, src) != "application" or src in seen:
                    continue
                # The Application Index lists every record, so it links to all
                # of them. A hub is not a precedent.
                if is_hub(_note_type(conn, src)):
                    continue
                seen.add(src)
                results.append(Result(
                    "application", src,
                    f"links to {target} via {relation}", 0.9,
                    _application_fields(conn, src)))

        scores, best, degraded, tier = _search(conn, resource_or_topic, cfg,
                                               layers=("application",), pool=40)
        for name, score in sorted(scores.items(), key=lambda kv: -kv[1]):
            if name in seen or len(results) >= limit:
                continue
            if is_hub(_note_type(conn, name)):
                continue
            seen.add(name)
            results.append(Result("application", name, _why(best.get(name), ""),
                                  score * 0.8, _application_fields(conn, name)))

        return Response(
            intent="precedent", results=tuple(results),
            tier_reached=3 if results else 1,
            next_step=("read 'What The Catalogue Should Learn' in each - that section "
                       "is where a record states a requirement rather than a memory"
                       if results else
                       "no precedent recorded. If you use it, write the record: an "
                       "unrecorded use teaches the catalogue nothing"),
            partial=bool(degraded), notes=tuple(degraded))
    finally:
        conn.close()


def get_note(name: str, *, db_path: Path | None = None) -> dict[str, Any]:
    """Tier 3, directly. Frontmatter and body, from the index."""
    conn = _conn(db_path)
    try:
        resolved = _resolve_note(conn, name)
        if not resolved:
            return {"found": False, "name": name,
                    "why": f"no note named '{name}'; names are the note's filename "
                           f"without .md"}
        row = conn.execute("SELECT * FROM note WHERE name = ?", (resolved,)).fetchone()
        return {"found": True, "name": row["name"], "layer": row["layer"],
                "type": row["type"], "path": row["path"],
                "frontmatter": json.loads(row["frontmatter"]),
                "body": row["body"],
                "links_out": [dict(r) for r in conn.execute(
                    "SELECT dst, relation FROM link WHERE src = ?", (resolved,))],
                "links_in": [dict(r) for r in conn.execute(
                    "SELECT src, relation FROM link WHERE dst = ?", (resolved,))]}
    finally:
        conn.close()


# ------------------------------------------------------- the one permitted write

REQUIRED_RECORD_FIELDS = ("project", "stage", "outcome")
RECORD_SECTIONS = ("What Was Needed", "What Was Found And Taken", "What It Replaced",
                   "What The Catalogue Should Learn")


def record_application(record: dict[str, Any], *, vault: Path | None = None,
                       db_path: Path | None = None,
                       attested_by: str = "agent") -> dict[str, Any]:
    """Append an application record. The single write Mode C may perform.

    Records written by a tool are marked `attested_by: agent` so they can be
    weighted differently from ones a person wrote. The value of this call is
    that writing a record is a tool call at the end of a task rather than a
    chore to remember afterwards - which is the difference between records
    accumulating and records not existing.
    """
    policy.check_consult_write("record_application")
    root = Path(vault) if vault else vault_root()

    missing = [f for f in REQUIRED_RECORD_FIELDS if not record.get(f)]
    if missing:
        raise ValueError(f"application record is missing required field(s): {missing}")
    if attested_by not in {"user", "agent"}:
        raise ValueError("attested_by must be 'user' or 'agent'")

    body_sections = record.get("sections") or {}
    empty = [s for s in RECORD_SECTIONS if not str(body_sections.get(s, "")).strip()]
    if empty:
        raise ValueError(
            f"an application record must answer every section; missing: {empty}. "
            f"'What The Catalogue Should Learn' is the one that turns a diary entry "
            f"into a requirement.")

    project = str(record["project"]).strip()
    title = record.get("title") or f"Application - {project}"
    safe = re.sub(r"[^A-Za-z0-9 &_.-]", "", str(title)).strip() or "Application - Untitled"
    path = root / "09-Applications" / f"{safe}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        raise FileExistsError(f"{path.name} already exists; edit it rather than "
                              f"writing a second record for the same engagement")

    frontmatter = {
        "type": "application_record",
        "project": project,
        "stage": record["stage"],
        "date_range": record.get("date_range", ""),
        "status": record.get("status", "active"),
        "resources_used": record.get("resources_used", []),
        "patterns_discovered": record.get("patterns_discovered", []),
        "domains": record.get("domains", []),
        "outcome": record["outcome"],
        "attested_by": attested_by,
    }
    lines = ["---"]
    for key, value in frontmatter.items():
        lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}"
                     if isinstance(value, (list, dict))
                     else f'{key}: "{value}"')
    lines.append("---")
    lines.append("")
    lines.append(f"# {safe}")
    for section in RECORD_SECTIONS:
        lines.append("")
        lines.append(f"## {section}")
        lines.append(str(body_sections[section]).strip())
    lines.append("")
    lines.append("## Semantic Links")
    lines.append("- [application_hub:: [[Application Index]]]")
    for resource in record.get("applied_resources", []):
        lines.append(f"- [applied_resource:: [[{resource}]]]")
    for topic in record.get("related_topics", []):
        lines.append(f"- [related_topic:: [[{topic}]]]")
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")

    # Markdown is truth; the index catches up. Failing to refresh must not
    # fail the write, because the note is already the authoritative record.
    refreshed = True
    try:
        index_mod.refresh(root, db_path, since=time.time() - 5)
    except Exception:                                       # pragma: no cover
        refreshed = False
    return {"path": str(path), "name": safe, "attested_by": attested_by,
            "index_refreshed": refreshed}


# ------------------------------------------------- typed params (spec 4.3/10.3)

SEARCH_PARAMS_SCHEMA: dict[str, Any] = {
    "$id": "catalogue/search_params/v1",
    "type": "object",
    "additionalProperties": False,
    "required": ["intent", "terms"],
    "properties": {
        "intent": {"enum": list(INTENTS)},
        "terms": {"type": "array", "items": {"type": "string"},
                  "minItems": 1, "maxItems": 8},
        "domain": {"type": "string", "description": "must exist in the domain register"},
        "filters": {
            "type": "object",
            "additionalProperties": False,
            "properties": {
                "license_class": {"enum": list(LICENSE_CLASSES)},
                "deployment_target": {"type": "string"},
                "hardware_footprint": {"type": "string"},
                "max_age_days": {"type": "integer", "minimum": 1},
            },
        },
        "source": {"type": "string", "description": "repo_key, for intent=technique"},
        "limit": {"type": "integer", "minimum": 1, "maximum": 50, "default": 10},
    },
}


def validate_params(params: dict[str, Any], *, vault: Path | None = None) -> dict[str, Any]:
    """Validate the one typed object a model is permitted to produce.

    `additionalProperties: false` throughout, enums closed, and `domain`
    checked against the register - so an invalid domain is a validation error
    rather than a silent miss, and the model cannot widen its own permissions
    by inventing a field.
    """
    from .integrity import known_topic_keys

    if not isinstance(params, dict):
        raise ValueError("search params must be an object")
    allowed = set(SEARCH_PARAMS_SCHEMA["properties"])
    unknown = set(params) - allowed
    if unknown:
        raise ValueError(f"unknown search parameter(s): {sorted(unknown)}")
    intent = params.get("intent")
    if intent not in INTENTS:
        raise ValueError(f"intent must be one of {list(INTENTS)}")
    terms = params.get("terms")
    if not isinstance(terms, list) or not 1 <= len(terms) <= 8 \
            or not all(isinstance(t, str) and t.strip() for t in terms):
        raise ValueError("terms must be 1-8 non-empty strings")

    filters = params.get("filters") or {}
    if not isinstance(filters, dict):
        raise ValueError("filters must be an object")
    filter_allowed = set(SEARCH_PARAMS_SCHEMA["properties"]["filters"]["properties"])
    unknown_filters = set(filters) - filter_allowed
    if unknown_filters:
        raise ValueError(f"unknown filter(s): {sorted(unknown_filters)}")
    if filters.get("license_class") and filters["license_class"] not in LICENSE_CLASSES:
        raise ValueError(f"license_class must be one of {list(LICENSE_CLASSES)}")
    if "max_age_days" in filters and (not isinstance(filters["max_age_days"], int)
                                      or filters["max_age_days"] < 1):
        raise ValueError("max_age_days must be a positive integer")

    domain = params.get("domain")
    if domain:
        known = known_topic_keys(Path(vault) if vault else vault_root())
        if domain not in known:
            raise ValueError(
                f"domain '{domain}' is not in the register. The scout may not invent "
                f"a domain; edit [[Scouting Domains]] to add one.")

    limit = params.get("limit", 10)
    if not isinstance(limit, int) or not 1 <= limit <= 50:
        raise ValueError("limit must be an integer between 1 and 50")

    return {"intent": intent, "terms": [t.strip() for t in terms], "domain": domain,
            "filters": dict(filters), "source": params.get("source"), "limit": limit}


def dispatch(params: dict[str, Any], *, db_path: Path | None = None,
             vault: Path | None = None, cfg: CatalogueConfig | None = None) -> Response:
    """Validate, then route to the query the intent names."""
    valid = validate_params(params, vault=vault)
    query = " ".join(valid["terms"])
    limit = valid["limit"]
    filters = dict(valid["filters"])
    if valid["domain"]:
        query = f"{query} {valid['domain']}"
    intent = valid["intent"]
    if intent == "orient":
        return orient(query, limit, db_path=db_path, cfg=cfg)
    if intent == "donor":
        return find_donor(query, filters, limit, db_path=db_path, cfg=cfg)
    if intent == "pattern":
        return find_pattern(query, limit, db_path=db_path, cfg=cfg)
    if intent == "technique":
        return find_technique(query, valid["source"], limit, db_path=db_path, cfg=cfg)
    if intent == "data":
        return find_data(query, None, limit, db_path=db_path, cfg=cfg)
    return find_precedent(query, limit, db_path=db_path, cfg=cfg)


