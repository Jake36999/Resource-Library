"""Mode C - the consult surface.

Six typed query kinds, one envelope. Read-only but for `record_application`,
which is the single permitted write and is gated by `policy.check_consult_write`.

Three properties are load-bearing and are the reason this module is shaped the
way it is:

**Constraints eliminate.** A GPU-only tool is not a lower-ranked answer for a
laptop; it is not an answer. Filters run before ranking and the count of what
they removed is returned, so a thin result set is explained rather than
mysterious.

**Every result says why.** `why` is assembled from which filters passed and
which terms matched - never generated by a model. A result that cannot explain
itself cannot be trusted or tuned.

**No model stands between the query and the index.** Structured filters,
FTS5 and vectors over verified notes cannot fabricate a resource, because they
can only return things that exist. A model may summarise afterwards.
"""
