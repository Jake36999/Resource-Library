def _top(scores: dict[str, float], best: dict[str, Hit], layers: Sequence[str],
         conn: sqlite3.Connection, limit: int) -> list[tuple[str, float, Hit | None]]:
    wanted = set(layers)
    out: list[tuple[str, float, Hit | None]] = []
    for name, score in sorted(scores.items(), key=lambda kv: -kv[1]):
        if _layer(conn, name) not in wanted:
            continue
        # A hub routes to answers; returning one as an answer is the retrieval
        # equivalent of handing somebody the index of a book they asked about.
        if is_hub(_note_type(conn, name)):
            continue
        out.append((name, score, best.get(name)))
        if len(out) >= limit:
            break
    return out


def _layer(conn: sqlite3.Connection, name: str) -> str:
    row = conn.execute("SELECT layer FROM note WHERE name = ?", (name,)).fetchone()
    return (row["layer"] or "") if row else ""


def _note_type(conn: sqlite3.Connection, name: str) -> str:
    row = conn.execute("SELECT type FROM note WHERE name = ?", (name,)).fetchone()
    return (row["type"] or "") if row else ""


def _resolve_note(conn: sqlite3.Connection, name: str) -> str | None:
    row = conn.execute("SELECT name FROM note WHERE name = ?", (name,)).fetchone()
    if row:
        return row["name"]
    row = conn.execute("SELECT name FROM note WHERE LOWER(name) = LOWER(?)",
                       (name,)).fetchone()
    if row:
        return row["name"]
    row = conn.execute(
        "SELECT name FROM resource_facet WHERE repo_key = ? OR canonical_url = ?",
        (name, name)).fetchone()
    return row["name"] if row else None


def _note_for_source(conn: sqlite3.Connection, source: str) -> str | None:
    row = conn.execute("SELECT name FROM resource_facet WHERE repo_key = ?",
                       (source,)).fetchone()
    if row:
        return row["name"]
    return _resolve_note(conn, source)


def _incoming(conn: sqlite3.Connection, dst: str, relation: str) -> list[str]:
    return [r["src"] for r in conn.execute(
        "SELECT src FROM link WHERE dst = ? AND relation = ?", (dst, relation))]


def _incoming_any(conn: sqlite3.Connection, dst: str) -> list[tuple[str, str]]:
    return [(r["src"], r["relation"]) for r in conn.execute(
        "SELECT src, relation FROM link WHERE dst = ?", (dst,))]


def _children_of(conn: sqlite3.Connection, topic: str) -> list[str]:
    return _incoming(conn, topic, "parent_topic")


def _parent_topic(conn: sqlite3.Connection, name: str) -> str:
    row = conn.execute(
        "SELECT dst FROM link WHERE src = ? AND relation = 'parent_topic'",
        (name,)).fetchone()
    return row["dst"] if row else ""


def _related_patterns(conn: sqlite3.Connection, pattern: str, limit: int = 4) -> list[str]:
    rows = conn.execute(
        "SELECT DISTINCT l2.src AS name FROM link l1 JOIN link l2 ON l1.dst = l2.dst "
        "JOIN note n ON n.name = l2.src "
        "WHERE l1.src = ? AND l2.src != ? AND n.layer = 'pattern' LIMIT ?",
        (pattern, pattern, limit)).fetchall()
    return [r["name"] for r in rows]


def _sources_with_access_points(conn: sqlite3.Connection) -> set[str]:
    return {row["source"] for row in conn.execute(
        "SELECT DISTINCT source FROM access_point")}


def _access_points_for(conn: sqlite3.Connection, sources: Sequence[str]) -> list[sqlite3.Row]:
    if not sources:
        return []
    keys = list(sources)
    for name in sources:
        row = conn.execute("SELECT repo_key FROM resource_facet WHERE name = ?",
                           (name,)).fetchone()
        if row and row["repo_key"]:
            keys.append(row["repo_key"])
    marks = ",".join("?" for _ in keys)
    return conn.execute(
        f"SELECT * FROM access_point WHERE source IN ({marks}) ORDER BY source, kind",
        keys).fetchall()


def _validation_criteria(conn: sqlite3.Connection, datasets: Sequence[str]
                         ) -> list[tuple[str, str]]:
    """Criteria come from application records, never from a model.

    `patterns_discovered` on a record is where a real engagement wrote down
    what "correct" looked like; anything else would be invention.
    """
    out: list[tuple[str, str]] = []
    rows = conn.execute(
        "SELECT name, frontmatter FROM note WHERE layer = 'application'").fetchall()
    for row in rows:
        try:
            data = json.loads(row["frontmatter"])
        except Exception:                                   # pragma: no cover
            continue
        for item in data.get("patterns_discovered") or []:
            text = str(item)
            if "valid" in text.lower() or "verif" in text.lower():
                out.append((row["name"], text))
    return out[:5]


