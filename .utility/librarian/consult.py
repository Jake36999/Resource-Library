def terms_from(text: str) -> list[str]:
    """Query text to search terms.

    Quoted phrases survive intact, because "change data capture" is one thing
    and three stopword-adjacent tokens are not.
    """
    out: list[str] = []
    for match in TOKEN.findall(text or ""):
        token = match.strip('"').strip()
        if not token:
            continue
        if token.lower() in STOPWORDS and " " not in token:
            continue
        if token.lower() not in [t.lower() for t in out]:
            out.append(token)
    return out



# Frontmatter fields whose values describe *what a note is about*, and are
# therefore worth matching a query against. The nine taxonomy axes are
# deliberately absent: they are filter fields, and their values are identifiers
# that collide with ordinary words. `interface_protocol: "REST"` matched the
# 'rest' in "the rest of the system is out of scope", putting an unrelated
# dataset above everything. A category is something you filter on, not
# something you free-text search.
MATCHABLE_FRONTMATTER = ("glossary_terms", "patterns", "aliases", "repo_key",
                         "canonical_word", "term_key", "pattern_key", "topic_key",
                         "primary_topic", "secondary_topics", "type", "project")


def _matched_frontmatter(raw: str | None, terms: Sequence[str]) -> list[str]:
    """Query terms appearing as a whole value in a content-bearing field."""
    try:
        data = json.loads(raw or "{}")
    except ValueError:                                        # pragma: no cover
        return []
    values: set[str] = set()
    for key in MATCHABLE_FRONTMATTER:
        value = data.get(key)
        if isinstance(value, str):
            values.add(value.lower())
        elif isinstance(value, (list, tuple)):
            values.update(str(v).lower() for v in value)
    return [t for t in terms if t.lower() in values]


def _matched_terms_bounded(text: str, terms: Sequence[str]) -> list[str]:
    """Like `_matched_terms`, but a term must be a whole token.

    Names are short, so a substring match inside an unrelated word is a large
    proportion of the evidence rather than noise: 'review' matched inside
    `asreview` put a systematic-screening tool at the top of a query about
    contribution workflows. Word boundaries here, substrings elsewhere - in a
    long body of prose a substring hit is usually the word you meant.
    """
    low = text.lower()
    return [t for t in terms
            if re.search(rf"(?<![a-z0-9]){re.escape(t.lower())}(?![a-z0-9])", low)]


def _fts_query(terms: Sequence[str]) -> str:
    quoted = ['"' + t.replace('"', '') + '"' for t in terms if t.strip()]
    return " OR ".join(quoted)


def _matched_terms(text: str, terms: Sequence[str]) -> list[str]:
    low = text.lower()
    return [t for t in terms if t.lower() in low]


@dataclass(frozen=True)
class Hit:
    note: str
    layer: str
    heading: str
    excerpt: str
    matched: tuple[str, ...]
    rank: int


def lexical(conn: sqlite3.Connection, terms: Sequence[str],
            layers: Sequence[str] | None = None, limit: int = 60) -> list[Hit]:
    """FTS5/BM25 over note prose.

    Lexical goes first because it answers what embeddings handle worst: rare,
    specific tokens - *does anything here read Parquet*.
    """
    query = _fts_query(terms)
    if not query:
        return []
    sql = ("SELECT c.id AS id, c.note AS note, c.layer AS layer, c.heading AS heading, "
           "c.text AS text, bm25(chunk_fts) AS rank "
           "FROM chunk_fts JOIN chunk c ON c.id = chunk_fts.rowid "
           "WHERE chunk_fts MATCH ?")
    params: list[Any] = [query]
    if layers:
        marks = ",".join("?" for _ in layers)
        sql += f" AND c.layer IN ({marks})"
        params.extend(layers)
    sql += " ORDER BY rank LIMIT ?"
    params.append(limit)
    try:
        rows = conn.execute(sql, params).fetchall()
    except sqlite3.OperationalError:
        return []
    hits: list[Hit] = []
    for position, row in enumerate(rows, start=1):
        text = row["text"]
        hits.append(Hit(note=row["note"], layer=row["layer"],
                        heading=row["heading"] or "",
                        excerpt=_excerpt(text, terms),
                        matched=tuple(_matched_terms(f"{row['heading']} {text}", terms)),
                        rank=position))
    return hits


# A name hit on one term out of ten is not evidence about the note; it is a
# coincidence of vocabulary. `run-llama - llama_index` matching 'run' in the
# query "run twelve dependent jobs nightly and recover from partial failure"
# outranked `apache - airflow`, which matched four terms in its own
# `What It Solves`. The name ranking is deliberately weighted above the text
# ranking, so a weak hit inside it beats a strong hit outside it.
#
# The rule below keeps the behaviour the docstring promises - a short,
# name-shaped query resolves by name - and refuses the coincidence case.
NAME_MIN_QUERY_COVERAGE = 0.5   # share of the query a single-term hit must reach
NAME_MIN_NAME_COVERAGE = 0.5    # or share of the note's own name it must cover
NAME_SHORT_QUERY = 2            # queries this short are name lookups by intent


def _name_coverage(name: str, term: str) -> float:
    """How much of the note's own name this term accounts for.

    Compared on letters and digits only, so punctuation and the `owner - repo`
    convention do not distort it. `plumbing` is most of `Topic - Plumbing`;
    `run` is a sixth of `run-llama - llama_index`.
    """
    flat = "".join(ch for ch in name.lower() if ch.isalnum())
    if not flat:
        return 0.0
    return len("".join(ch for ch in term.lower() if ch.isalnum())) / len(flat)


def _name_hit_qualifies(matched: Sequence[str], terms: Sequence[str],
                        name: str = "") -> bool:
    """A name match earns its weighted ranking slot, or it does not appear.

    Two or more distinct query terms in one name is evidence on any query
    length. A single term is evidence when it is most of what was asked for,
    **or** most of what the note is called - and those are different tests.
    `orient("plumbing scheduler queue")` should still reach `Topic - Plumbing`,
    whose whole name is the matched term, while the same one-in-three coverage
    from `run` inside `run-llama - llama_index` is a coincidence of vocabulary.
    """
    if not matched or not terms:
        return False
    if len(terms) <= NAME_SHORT_QUERY:
        return True
    if len(matched) >= 2:
        return True
    if (len(matched) / len(terms)) >= NAME_MIN_QUERY_COVERAGE:
        return True
    return any(_name_coverage(name, term) >= NAME_MIN_NAME_COVERAGE
               for term in matched)


def by_name(conn: sqlite3.Connection, terms: Sequence[str],
            layers: Sequence[str] | None = None, limit: int = 30) -> list[Hit]:
    """Name and alias matching.

    Tier 1 of the cost ladder: *what is where*, answered without touching
    prose. `orient("airflow")` should find the Airflow note by its name, not
    by whichever paragraph happens to say the word most often.

    Two things are load-bearing here and were not always true. Hits are
    ordered by how much of the query they actually matched, not by whatever
    order SQLite returned the rows in - the position becomes the RRF rank, so
    row order was silently deciding relevance. And a hit must qualify under
    `_name_hit_qualifies` before it occupies a slot at all.
    """
    if not terms:
        return []
    clauses, params = [], []
    for term in terms:
        clauses.append("(LOWER(n.name) LIKE ? OR LOWER(n.frontmatter) LIKE ?)")
        params.extend([f"%{term.lower()}%", f'%"{term.lower()}"%'])
    sql = (f"SELECT n.name, n.layer, n.body, n.frontmatter FROM note n "
           f"WHERE ({' OR '.join(clauses)})")
    if layers:
        marks = ",".join("?" for _ in layers)
        sql += f" AND n.layer IN ({marks})"
        params.extend(layers)
    sql += " LIMIT ?"
    params.append(limit)
    rows = conn.execute(sql, params).fetchall()

    # A prose query carries words no stoplist catches - "Our", "Some", "we",
    # "review". Matching those against a note *name* and calling it evidence is
    # how "our reference manual carries code samples that were correct when
    # written" came back ranked on 'Our', 'Some', 'we'. Selectivity is measured
    # from the index, so the judgement is about this corpus rather than about
    # English.
    selective = _selective_terms(conn, terms)

    candidates: list[dict] = []
    for row in rows:
        # Which field actually matched, and nothing invented when none did.
        # An earlier version fell back to "the first search term" here, which
        # produced explanations asserting matches that had not happened.
        in_name = [t for t in _matched_terms_bounded(row["name"], terms)
                   if t.lower() in selective]
        matched = tuple(in_name)
        heading = "name" if in_name else "frontmatter"
        if not matched:
            matched = tuple(t for t in _matched_frontmatter(row["frontmatter"], terms)
                            if t.lower() in selective)
        if not matched:
            continue
        if not _name_hit_qualifies(matched, terms,
                                   row["name"] if in_name else ""):
            continue
        candidates.append({"name": row["name"], "layer": row["layer"],
                           "body": row["body"], "matched": matched,
                           "heading": heading})

    # More matched terms first; a name match ahead of a frontmatter-only match
    # on the same count; then the shorter name, which is the more specific one
    # when both contain the same term. Deterministic, so a rebuild reproduces
    # the same ranking.
    candidates.sort(key=lambda c: (-len(c["matched"]),
                                   0 if c["heading"] == "name" else 1,
                                   len(c["name"]), c["name"]))

    return [Hit(note=c["name"], layer=c["layer"], heading=c["heading"],
                excerpt=_excerpt(c["body"], terms), matched=c["matched"],
                rank=position)
            for position, c in enumerate(candidates, start=1)]


def _excerpt(text: str, terms: Sequence[str], width: int = 220) -> str:
    flat = " ".join((text or "").split())
    low = flat.lower()
    for term in terms:
        position = low.find(term.lower())
        if position >= 0:
            start = max(0, position - width // 3)
            return ("..." if start else "") + flat[start:start + width].strip() + \
                   ("..." if start + width < len(flat) else "")
    return flat[:width]


def rrf(rankings: Sequence[Sequence[str]], k: int = 60,
        weights: Sequence[float] | None = None) -> dict[str, float]:
    """Reciprocal Rank Fusion.

    Chosen over score blending because it needs no calibration between a BM25
    score and a cosine similarity, and each contributor stays inspectable.
    """
    weights = list(weights or [1.0] * len(rankings))
    scores: dict[str, float] = {}
    for ranking, weight in zip(rankings, weights):
        for position, name in enumerate(ranking, start=1):
            scores[name] = scores.get(name, 0.0) + weight / (k + position)
    return scores


def _normalise(scores: dict[str, float]) -> dict[str, float]:
    if not scores:
        return {}
    top = max(scores.values()) or 1.0
    return {name: value / top for name, value in scores.items()}


# --------------------------------------------------------------- hard filters

def eligible(conn: sqlite3.Connection, constraints: Constraints,
             candidates: Iterable[str] | None = None) -> tuple[set[str], int, str]:
    """Apply the hard filters. Returns (surviving names, eliminated, description).

    A resource whose value for a filtered axis is unknown is eliminated too.
    That is deliberate: "we do not know whether this runs on a laptop" is not
    an answer to "what runs on a laptop".
    """
    sql = "SELECT name, pushed_at, is_container FROM resource_facet WHERE 1=1"
    params: list[Any] = []
    for name in FILTER_FIELDS:
        values = getattr(constraints, name)
        if not values:
            continue
        marks = ",".join("?" for _ in values)
        sql += f" AND {name} IN ({marks})"
        params.extend(values)
    if constraints.exclude_containers:
        sql += " AND is_container = 0"
    rows = conn.execute(sql, params).fetchall()

    survivors = {row["name"] for row in rows}
    if constraints.max_age_days:
        horizon = datetime.now(timezone.utc) - timedelta(days=constraints.max_age_days)
        fresh = set()
        for row in rows:
            pushed = _parse_iso(row["pushed_at"])
            if pushed and pushed >= horizon:
                fresh.add(row["name"])
        survivors = fresh

    total = conn.execute("SELECT COUNT(*) AS n FROM resource_facet").fetchone()["n"]
    if candidates is not None:
        pool = set(candidates)
        eliminated = len(pool - survivors)
        survivors &= pool
    else:
        eliminated = total - len(survivors)
    return survivors, eliminated, constraints.describe()


def _parse_iso(value: str | None) -> datetime | None:
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


