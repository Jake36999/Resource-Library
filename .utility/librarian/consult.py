# --------------------------------------------------------------- the envelope

@dataclass(frozen=True)
class Result:
    """Contract per spec 9.2."""

    kind: str            # resource | topic | pattern | application | dataset
                         # | access_point | criterion | aggregator | note
    name: str
    why: str             # REQUIRED - assembled, never generated
    score: float         # 0..1, comparable only within one response
    fields: dict = field(default_factory=dict)


@dataclass(frozen=True)
class Response:
    """Contract per spec 9.2."""

    intent: str
    results: tuple[Result, ...] = ()
    # The drop-downs and the size of the set they describe. Empty for intents
    # that do not filter; `matched` is the whole candidate set, `results` the
    # page of it that came back.
    facets: dict = field(default_factory=dict)
    # Three different quantities, and a cold agent reasonably tried to add two
    # of them together. `considered` is every resource the filters were applied
    # to; `filtered_out` is how many of those a constraint removed; `matched`
    # is how many survivors also matched the query. `matched + filtered_out`
    # does not equal `considered`, because most survivors match no term at all.
    considered: int = 0
    matched: int = 0
    # Addresses *inside* the sources above - a different grain, kept in its own
    # field so `limit` means one thing and a caller never has to notice a
    # change of `kind` mid-list.
    components: tuple[Result, ...] = ()
    # Things a ranked list cannot say about itself: that a constraint removed a
    # better answer, or that nothing here really covers the question.
    advisories: tuple[str, ...] = ()
    filtered_out: int = 0
    tier_reached: int = 1        # 1 index | 2 metadata | 3 notes
    next_step: str = ""
    partial: bool = False
    notes: tuple[str, ...] = ()

    def grouped(self) -> dict[str, list[Result]]:
        """Results by kind - `orient()` returns topics, resources and
        aggregators, and this is how a caller separates them."""
        out: dict[str, list[Result]] = {}
        for result in self.results:
            out.setdefault(result.kind, []).append(result)
        return out

    def to_dict(self) -> dict[str, Any]:
        return {
            "intent": self.intent,
            "results": [
                {"kind": r.kind, "name": r.name, "why": r.why,
                 "score": round(r.score, 4), "fields": r.fields}
                for r in self.results
            ],
            "facets": self.facets,
            "considered": self.considered,
            "matched": self.matched,
            "components": [
                {"kind": c.kind, "name": c.name, "why": c.why,
                 "score": round(c.score, 4), "fields": c.fields}
                for c in self.components],
            "advisories": list(self.advisories),
            "filtered_out": self.filtered_out,
            "tier_reached": self.tier_reached,
            "next_step": self.next_step,
            "partial": self.partial,
            "notes": list(self.notes),
        }



def axis_vocabulary() -> dict[str, tuple[str, ...]]:
    """The permitted value of every filterable axis, from the content model.

    [[Note Content Model]] is the authority and already parses into
    `content_model.axis_values`; reading it here means the vocabulary a caller
    is offered and the vocabulary `integrity` enforces cannot drift apart.

    Degrades to empty when the model is absent, in which case values are not
    checked - the same posture the shape checks take.
    """
    try:
        from .content_model import load as load_model

        model = load_model()
        return {axis: tuple(sorted(values))
                for axis, values in (model.axis_values or {}).items()}
    except Exception:
        return {}


def _check_axis_values(axis: str, values: Sequence[str]) -> None:
    """Refuse a value outside the axis, and say what the axis permits.

    Before 2026-09-06 an unrecognised value simply matched nothing, so
    `license_class="permissive"` - the obvious English guess, wrong only in
    case - returned `matched: 0, filtered_out: 130` and a next step reading
    *every candidate failed a constraint*. That is a true sentence about a
    false premise: nothing failed the constraint, the constraint was not a
    constraint. A cold agent hit this within two calls.
    """
    permitted = axis_vocabulary().get(axis)
    if not permitted:
        return
    unknown = [v for v in values if v not in permitted]
    if unknown:
        raise ValueError(
            f"{axis}={unknown[0]!r} is not a value of that axis. Permitted: "
            f"{list(permitted)}. Values are case-sensitive.")

@dataclass(frozen=True)
class Constraints:
    """Hard filters. Every field eliminates; none of them re-ranks."""

    license_class: tuple[str, ...] = ()
    deployment_target: tuple[str, ...] = ()
    hardware_footprint: tuple[str, ...] = ()
    ecosystem: tuple[str, ...] = ()
    domain_primary: tuple[str, ...] = ()
    maturity_stage: tuple[str, ...] = ()
    interface_protocol: tuple[str, ...] = ()
    data_locality: tuple[str, ...] = ()
    security_compliance: tuple[str, ...] = ()
    agent_surface: tuple[str, ...] = ()
    max_age_days: int | None = None
    exclude_containers: bool = False

    @classmethod
    def of(cls, raw: dict[str, Any] | "Constraints" | None) -> "Constraints":
        if isinstance(raw, Constraints):
            return raw
        raw = dict(raw or {})
        kwargs: dict[str, Any] = {}
        unknown = set(raw) - set(cls.__dataclass_fields__)
        if unknown:
            raise ValueError(
                f"unknown constraint(s): {sorted(unknown)}. Filterable axes are "
                f"{list(FILTER_FIELDS)} plus max_age_days and exclude_containers.")
        for key, value in raw.items():
            if key in FILTER_FIELDS:
                if value in (None, "", []):
                    continue
                values = (value,) if isinstance(value, str) else tuple(value)
                _check_axis_values(key, values)
                kwargs[key] = values
            elif value not in (None, ""):
                kwargs[key] = value
        return cls(**kwargs)

    def active(self) -> dict[str, Any]:
        out: dict[str, Any] = {}
        for name in FILTER_FIELDS:
            values = getattr(self, name)
            if values:
                out[name] = list(values)
        if self.max_age_days:
            out["max_age_days"] = self.max_age_days
        if self.exclude_containers:
            out["exclude_containers"] = True
        return out

    def describe(self) -> str:
        parts = [f"{k}={'|'.join(v) if isinstance(v, list) else v}"
                 for k, v in self.active().items()]
        return ", ".join(parts)


